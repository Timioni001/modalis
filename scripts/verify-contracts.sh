#!/usr/bin/env bash
#
# MODALIS — publish the source of every testnet contract on the Monad explorer, and write the
# address list the hackathon rules ask for.
#
#   bash scripts/verify-contracts.sh
#
# Verifies through Sourcify (Monad's explorer reads from it), so no API key is needed and the
# constructor arguments are taken from each contract's creation transaction. Then writes
# docs/testnet-contracts.md: every address with its explorer link, ready to commit.
#
# Safe to rerun: an already-verified contract is reported and skipped.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"
export PATH="$HOME/.foundry/bin:$PATH"

KEEP="contracts/deployments/10143.testnet.json"
[ -f "$KEEP" ] || { echo "No $KEEP. Run bash scripts/go-live.sh first."; exit 1; }
VERIFIER_URL="${SOURCIFY_URL:-https://sourcify-api-monad.blockvision.org}"
EXPLORER="${NEXT_PUBLIC_MONAD_EXPLORER_URL:-https://testnet.monadexplorer.com}"

# key | source path:contract | what it is
ROWS="$(cat <<'MAP'
assetRegistry|src/AssetRegistry.sol:AssetRegistry|Which assets a plan may hold, and their limits
portfolioMandate|src/PortfolioMandate.sol:PortfolioMandate|Each person's plan and the four limits they approved
portfolioVault|src/PortfolioVault.sol:PortfolioVault|Holds each person's money; only they can withdraw
rebalanceExecutor|src/RebalanceExecutor.sol:RebalanceExecutor|Checks every adjustment against the plan before it runs
riskSignalReceiver|src/RiskSignalReceiver.sol:RiskSignalReceiver|Receives Chainlink CRE risk reports
priceOracle|src/mocks/MockPriceOracle.sol:MockPriceOracle|Demo prices (test network only)
executionAdapter|src/mocks/MockExecutionAdapter.sol:MockExecutionAdapter|Demo trading venue (test network only)
kuruAdapter|src/adapters/KuruAdapter.sol:KuruAdapter|Trades through Kuru's order book
mUSD|src/mocks/MockERC20.sol:MockERC20|Demo dollar token (test network only)
mBTC|src/mocks/MockERC20.sol:MockERC20|Demo bitcoin token (test network only)
mETH|src/mocks/MockERC20.sol:MockERC20|Demo ether token (test network only)
mBOND|src/mocks/MockERC20.sol:MockERC20|Demo bond token (test network only)
MAP
)"

addr_of() { node -p "const d=require('./$KEEP'); ({...d.contracts,...d.tokens})['$1'] || ''"; }

(cd contracts && forge build >/dev/null) || { echo "forge build failed; run it in contracts/ to see why."; exit 1; }

OUT="docs/testnet-contracts.md"
{
  echo "# Modalis on Monad testnet"
  echo
  echo "Chain id 10143. Source verified on the Monad explorer via Sourcify. Generated by \`scripts/verify-contracts.sh\`."
  echo
  echo "| Contract | Address | What it does |"
  echo "|---|---|---|"
} >"$OUT"

FAILED=0
while IFS='|' read -r key path what; do
  addr="$(addr_of "$key")"
  if [ -z "$addr" ] || [ "${addr,,}" = "0x0000000000000000000000000000000000000000" ]; then
    printf '  %-18s not deployed, skipped\n' "$key"; continue
  fi
  name="${path##*:}"
  log="$(cd contracts && forge verify-contract "$addr" "$path" --chain 10143 \
          --verifier sourcify --verifier-url "$VERIFIER_URL" 2>&1)"; rc=$?
  if [ "$rc" = "0" ] || printf '%s' "$log" | grep -qi "already verified"; then
    printf '  \033[32m✓\033[0m %-18s %s\n' "$key" "$addr"
  else
    FAILED=1
    printf '  \033[33m•\033[0m %-18s %s  (not verified: %s)\n' "$key" "$addr" "$(printf '%s' "$log" | tail -1)"
  fi
  label="$name"; case "$key" in m*) [ "$name" = "MockERC20" ] && label="$key ($name)";; esac
  echo "| $label | [\`$addr\`]($EXPLORER/address/$addr) | $what |" >>"$OUT"
done <<<"$ROWS"

block="$(node -p "require('./$KEEP').blockNumber || ''")"
[ -n "$block" ] && printf '\nDeployed at block %s.\n' "$block" >>"$OUT"

echo
echo "Wrote $OUT. Commit it so the README can link to it:"
echo "  git add $OUT && git commit -m 'List testnet contracts' && git push"
[ "$FAILED" = "0" ] || echo "Some contracts didn't verify; rerun later, or paste the lines above into the project thread."
