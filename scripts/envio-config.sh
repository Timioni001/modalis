#!/usr/bin/env bash
# Writes integrations/envio/config.hosted.yaml with this deployment's real addresses filled in.
#
# Envio's free hosted plan has no environment variables, so the ${...} placeholders in config.yaml
# can't be set there. Contract addresses and the start block are public, so it is safe to commit
# them. Point the hosted indexer's "Config File" at config.hosted.yaml.
#
#   bash scripts/envio-config.sh
set -euo pipefail
cd "$(dirname "$0")/.."

KEEP="contracts/deployments/10143.testnet.json"
[ -f "$KEEP" ] || { echo "No $KEEP. Run bash scripts/go-live.sh first."; exit 1; }

node - "$KEEP" <<'EOF'
const fs = require("fs");
const d = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const c = d.contracts || {};
const zero = /^0x0{40}$/i;
const has = (a) => typeof a === "string" && /^0x[0-9a-fA-F]{40}$/.test(a) && !zero.test(a);
const vals = {
  ENVIO_START_BLOCK: String(d.blockNumber ?? 0),
  MONAD_TESTNET_RPC_URL: process.env.MONAD_TESTNET_RPC_URL || "https://testnet-rpc.monad.xyz",
  NEXT_PUBLIC_PORTFOLIO_MANDATE_ADDRESS: c.portfolioMandate,
  NEXT_PUBLIC_PORTFOLIO_VAULT_ADDRESS: c.portfolioVault,
  NEXT_PUBLIC_REBALANCE_EXECUTOR_ADDRESS: c.rebalanceExecutor,
  NEXT_PUBLIC_RISK_SIGNAL_RECEIVER_ADDRESS: c.riskSignalReceiver,
};
for (const k of ["NEXT_PUBLIC_PORTFOLIO_MANDATE_ADDRESS", "NEXT_PUBLIC_PORTFOLIO_VAULT_ADDRESS", "NEXT_PUBLIC_REBALANCE_EXECUTOR_ADDRESS"]) {
  if (!has(vals[k])) { console.error(`Missing ${k} in ${process.argv[2]}`); process.exit(1); }
}
let text = fs.readFileSync("integrations/envio/config.yaml", "utf8");
// No risk receiver deployed yet: drop it from the chain's contract list rather than index 0x0.
if (!has(vals.NEXT_PUBLIC_RISK_SIGNAL_RECEIVER_ADDRESS)) {
  text = text.replace(/\n\s*- name: RiskSignalReceiver\n\s*address: \$\{NEXT_PUBLIC_RISK_SIGNAL_RECEIVER_ADDRESS\}/, "");
  console.log("No riskSignalReceiver yet; leaving it out of the hosted config.");
}
text = text.replace(/\$\{(\w+)\}/g, (m, k) => (k in vals && vals[k] ? vals[k] : m));
const left = text.match(/\$\{\w+\}/g);
if (left) { console.error(`Unfilled: ${left.join(", ")}`); process.exit(1); }
fs.writeFileSync("integrations/envio/config.hosted.yaml",
  "# Generated by scripts/envio-config.sh from config.yaml. Do not edit by hand.\n" + text);
console.log("Wrote integrations/envio/config.hosted.yaml");
EOF
