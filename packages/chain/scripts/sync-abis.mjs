#!/usr/bin/env node
/**
 * Generates typed ABI modules from the Foundry build output.
 *
 * The ABIs the app talks to are therefore always the ABIs of the contracts that were
 * actually compiled — never hand-transcribed. Run `forge build` first, then:
 *
 *   pnpm --filter @modalis/chain sync-abis
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, "../../../contracts/out");
const abiDir = resolve(here, "../src/abis");

/** Contracts whose ABI the application needs. */
const CONTRACTS = [
  "AssetRegistry",
  "PortfolioMandate",
  "PortfolioVault",
  "RebalanceExecutor",
  "RiskSignalReceiver",
  "KuruAdapter",
  "MockERC20",
  "MockPriceOracle",
  "MockExecutionAdapter",
];

mkdirSync(abiDir, { recursive: true });

const written = [];
for (const name of CONTRACTS) {
  const artifact = join(outDir, `${name}.sol`, `${name}.json`);
  let json;
  try {
    json = JSON.parse(readFileSync(artifact, "utf8"));
  } catch {
    console.warn(`skip ${name}: no artifact at ${artifact} (run \`forge build\`)`);
    continue;
  }
  const file = `// Generated by scripts/sync-abis.mjs from contracts/out/${name}.sol/${name}.json
// Do not edit by hand. Run \`pnpm --filter @modalis/chain sync-abis\` after \`forge build\`.
export const ${name}Abi = ${JSON.stringify(json.abi, null, 2)} as const;
`;
  writeFileSync(join(abiDir, `${name}.ts`), file);
  written.push(name);
}

const index = `// Generated by scripts/sync-abis.mjs. Do not edit by hand.
${written.map((n) => `export { ${n}Abi } from "./${n}.ts";`).join("\n")}
`;
writeFileSync(join(abiDir, "index.ts"), index);
console.log(`wrote ${written.length} ABIs: ${written.join(", ")}`);
