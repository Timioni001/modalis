#!/usr/bin/env node
/**
 * Generates TypeScript row types from the LIVE database schema.
 *
 * Same principle as the contract ABIs: the types the app compiles against are derived from the
 * thing they describe, not hand-transcribed beside it. A column renamed in
 * supabase/migrations/0001_init.sql shows up here as a type error instead of a runtime surprise.
 *
 *   bash scripts/db-local.sh up
 *   SUPABASE_DB_URL="$(bash scripts/db-local.sh url)" pnpm --filter @modalis/db gen-types
 *
 * Uses psql rather than a driver so the package needs no Postgres client dependency just to
 * build its types.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const outFile = resolve(here, "../src/types.generated.ts");

const url = process.env.SUPABASE_DB_URL;
if (!url) {
  console.error("SUPABASE_DB_URL is required. Try:");
  console.error('  SUPABASE_DB_URL="$(bash scripts/db-local.sh url)" pnpm --filter @modalis/db gen-types');
  process.exit(1);
}

const q = (sql) =>
  execFileSync("psql", [url, "-At", "-F", "\u0001", "-c", sql], { encoding: "utf8" })
    .trim()
    .split("\n")
    .filter(Boolean)
    .map((line) => line.split("\u0001"));

// ------------------------------------------------------------------ enums
const enumRows = q(`
  select t.typname, e.enumlabel
  from pg_type t
  join pg_enum e on e.enumtypid = t.oid
  join pg_namespace n on n.oid = t.typnamespace
  where n.nspname = 'public'
  order by t.typname, e.enumsortorder
`);

const enums = new Map();
for (const [name, label] of enumRows) {
  if (!enums.has(name)) enums.set(name, []);
  enums.get(name).push(label);
}

// ---------------------------------------------------------------- columns
const colRows = q(`
  select c.table_name, c.column_name, c.is_nullable, c.data_type, c.udt_name,
         case when c.column_default is not null or c.is_identity = 'YES' then 'yes' else 'no' end
  from information_schema.columns c
  join information_schema.tables t
    on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position
`);

/**
 * numeric is mapped to `string`, not `number`.
 *
 * These columns hold money and token amounts — numeric(78,0) holds a uint256, which no JS number
 * can represent. supabase-js returns numeric as a string, and callers convert to BigInt. Mapping
 * it to `number` would silently corrupt balances above 2^53.
 */
function tsType(dataType, udt) {
  if (udt.startsWith("_")) return `${tsType("", udt.slice(1))}[]`;
  if (enums.has(udt)) return pascal(udt);
  switch (udt) {
    case "uuid":
    case "text":
    case "varchar":
    case "date":
    case "timestamptz":
    case "timestamp":
      return "string";
    case "numeric":
      return "string"; // money / uint256 — never number
    case "int2":
    case "int4":
    case "float4":
    case "float8":
      return "number";
    case "int8":
      return "string"; // bigint; out of safe-integer range
    case "bool":
      return "boolean";
    case "jsonb":
    case "json":
      return "Json";
    default:
      return "unknown";
  }
}

const pascal = (s) => s.replace(/(^|_)([a-z])/g, (_, __, c) => c.toUpperCase());
const singular = (s) => (s.endsWith("ies") ? `${s.slice(0, -3)}y` : s.endsWith("s") ? s.slice(0, -1) : s);

const tables = new Map();
for (const [table, column, nullable, dataType, udt, hasDefault] of colRows) {
  if (!tables.has(table)) tables.set(table, []);
  tables.get(table).push({
    column,
    nullable: nullable === "YES",
    type: tsType(dataType, udt),
    hasDefault: hasDefault === "yes",
  });
}

// ----------------------------------------------------------------- emit
let out = `// Generated by scripts/generate-types.mjs from the live database schema.
// Do not edit by hand. Regenerate after changing supabase/migrations/0001_init.sql:
//   SUPABASE_DB_URL="$(bash scripts/db-local.sh url)" pnpm --filter @modalis/db gen-types
//
// NOTE: \`numeric\` columns are typed as \`string\`, not \`number\`. They hold USD at 1e18 and
// uint256 token amounts, which no JS number can represent. Convert with BigInt().

export type Json = string | number | boolean | null | Json[] | { [key: string]: Json };
`;

for (const [name, labels] of enums) {
  out += `\nexport type ${pascal(name)} = ${labels.map((l) => `"${l}"`).join(" | ")};\n`;
  // goal_status -> GOAL_STATUS_VALUES
  out += `export const ${name.toUpperCase()}_VALUES = [${labels.map((l) => `"${l}"`).join(", ")}] as const;\n`;
}

for (const [table, cols] of tables) {
  const Row = `${pascal(singular(table))}Row`;
  out += `\n/** public.${table} */\nexport type ${Row} = {\n`;
  for (const c of cols) {
    out += `  ${c.column}: ${c.type}${c.nullable ? " | null" : ""};\n`;
  }
  out += `};\n`;

  // Insert type: columns with a default or that are nullable are optional.
  out += `\nexport type ${pascal(singular(table))}Insert = {\n`;
  for (const c of cols) {
    const optional = c.hasDefault || c.nullable;
    out += `  ${c.column}${optional ? "?" : ""}: ${c.type}${c.nullable ? " | null" : ""};\n`;
  }
  out += `};\n`;
}

out += `\n/** Every table, for the typed supabase-js client. */\nexport type Database = {\n  public: {\n    Tables: {\n`;
for (const [table] of tables) {
  const base = pascal(singular(table));
  // `Relationships` is required by postgrest-js's GenericTable constraint. Without it the whole
  // Database type silently fails to satisfy GenericSchema and every query resolves to `never`.
  // Left empty because the repositories use explicit queries rather than embedded joins.
  out += `      ${table}: { Row: ${base}Row; Insert: ${base}Insert; Update: Partial<${base}Insert>; Relationships: [] };\n`;
}
out += `    };\n    Views: Record<string, never>;\n    Functions: Record<string, never>;\n    Enums: {\n`;
for (const [name] of enums) out += `      ${name}: ${pascal(name)};\n`;
out += `    };\n  };\n};\n`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`wrote ${outFile}`);
console.log(`  ${tables.size} tables, ${enums.size} enums`);
